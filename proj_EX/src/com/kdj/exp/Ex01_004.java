package com.kdj.exp;

public class Ex01_004 {

	public static void main(String[] args) {
//		비교 연산자
		int a = 1;
		int b = 5;
//		비교 연산자는 참/거짓(boolean)으로 답한다.
		System.out.println("int a = 1\nint b = 5");
		System.out.println("a < b: " + (a < b));
		System.out.println("a >= b: " + (a >= b));
		System.out.println("a != b: " + (a != b));
		System.out.println("a == b: " + (a == b));
		
	}

}
