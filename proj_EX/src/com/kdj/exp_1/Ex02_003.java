package com.kdj.exp_1;

public class Ex02_003 {

	public static void main(String[] args) {
		System.out.println("최댓값: " + Math.max(10, 20));
		System.out.println("최솟값: " + Math.min(10, 20));
		System.out.println("절댓값: " + Math.abs(-15));
		System.out.println("2의 3제곱: " + Math.pow(2, 3));
		System.out.println("64의 제곱근: " + Math.sqrt(64));
		System.out.println("반올림: " + Math.round(3.7));
		System.out.println("올림: " + Math.ceil(3.1));
		System.out.println("내림: " + Math.floor(3.9));
	}

}
