package com.kdj.exp_1;

public class Ex01_003 {

	public static void main(String[] args) {
//		대입 연산자

		int num = 1;
		System.out.println("int num = 1"); // 1
		num += 5;
		System.out.println("num += 5: " + num); // 6
		num -= 3;
		System.out.println("num -= 3: " + num); // 3
		num *= 2;
		System.out.println("num *= 2: " + num); // 6
		num /= 2;
		System.out.println("num /= 2: " + num); // 3
		num %= 2;
		System.out.println("num %= 2: " + num); // 1
		
		
				
	}

}
